def backup_file(filepath):
    """Crea copia de seguridad del fichero."""
    backup = filepath + ".bak_" + datetime.now().strftime("%Y%m%d_%H%M%S")
    shutil.copy2(filepath, backup)
    return backup

def apply_move_names(filepath, translations, dry_run=False):
    """Reemplaza nombres en COMPOUND_STRING("NAME") en moves_info.h."""
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    count = 0
    for en, es in translations.items():
        pattern = r'(\.name\s*=\s*COMPOUND_STRING\s*\(\s*")' + re.escape(en) + r'("\s*\))'
        replacement = r'\g<1>' + es + r'\g<2>'
        new_content, n = re.subn(pattern, replacement, content)
        if n > 0:
            count += n
            content = new_content

    if not dry_run and count > 0:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

    return count

