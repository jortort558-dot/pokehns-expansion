def apply_item_names(filepath, translations, dry_run=False):
    """Reemplaza nombres de objetos en ITEM_NAME("NAME")."""
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    count = 0
    for en, es in translations.items():
        # items.h usa ITEM_NAME("NAME") o COMPOUND_STRING("NAME")
        for macro in ["ITEM_NAME", "COMPOUND_STRING"]:
            pattern = r'(' + macro + r'\s*\(\s*")' + re.escape(en) + r'("\s*\))'
            replacement = r'\g<1>' + es + r'\g<2>'
            new_content, n = re.subn(pattern, replacement, content)
            if n > 0:
                count += n
                content = new_content

    if not dry_run and count > 0:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

    return count

def main():
    project_dir = sys.argv[1] if len(sys.argv) > 1 else "."
    dry_run = "--dry-run" in sys.argv

    if dry_run:
        print("[MODO SIMULACIÓN - No se escriben cambios]")

    moves_file    = os.path.join(project_dir, "src", "data", "moves_info.h")
    abilities_file = os.path.join(project_dir, "src", "data", "abilities.h")
    items_file    = os.path.join(project_dir, "src", "data", "items.h")

    print("=" * 60)
    print("  TRADUCCIÓN FASE 1 - Pokémon Heart & Soul (HNS)")
    print("=" * 60)

    for label, filepath, func, trans in [
        ("Movimientos (nombres)",  moves_file,     apply_move_names,    MOVE_NAMES),
        ("Habilidades (nombres)",  abilities_file,  apply_ability_names, ABILITY_NAMES),
        ("Objetos (nombres)",      items_file,      apply_item_names,    ITEM_NAMES),
    ]:
        if not os.path.exists(filepath):
            print(f"\n  [SKIP] {label}: {filepath} no encontrado")
            continue

        if not dry_run:
            bak = backup_file(filepath)
            print(f"\n  [BAK] {os.path.basename(bak)}")

        n = func(filepath, trans, dry_run=dry_run)
        status = "OK" if n > 0 else "SIN CAMBIOS"
        print(f"  [{status}] {label}: {n} sustituciones")

    print("\n" + "=" * 60)
    print("  LISTO - Ejecuta 'make modern' para compilar")
    print("=" * 60)

if __name__ == "__main__":
    main()
